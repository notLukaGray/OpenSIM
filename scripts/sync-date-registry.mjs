// Regenerates content/date-registry.generated.ts from content/dates/*.json.
// Run after adding/removing date files: node scripts/sync-date-registry.mjs
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const datesDir = path.join(root, "content", "dates");
const outPath = path.join(root, "content", "date-registry.generated.ts");

const files = readdirSync(datesDir)
  .filter((f) => f.endsWith(".json"))
  .sort();

const lines = [
  "// AUTO-GENERATED by scripts/sync-date-registry.mjs — do not edit by hand.",
  "// Add/remove a file in content/dates/ then run `npm run sync:dates`.",
  "import type { DateTree } from './schema';",
  ...files.map((f, i) => `import d${i} from "./dates/${f}";`),
  "",
  `// eslint-disable-next-line`,
  `// JSON literals widen string unions; runtime shape is guarded in registry.ts`,
  `// and semantics by tools/validate-core.mjs.`,
  `export const dateFiles = [${files.map((_, i) => `d${i} as unknown as DateTree`).join(", ")}];`,
  "",
];

writeFileSync(outPath, lines.join("\n"));
console.log(`✓ date-registry.generated.ts (${files.length} trees): ${files.map((f) => f.replace(".json", "")).join(", ")}`);
